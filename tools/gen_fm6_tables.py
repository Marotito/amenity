"""Amenity+ F6d: the tables of the FM6 core (app/jungle/fm6_core.h: msfa, Dexed's 6-operator FM, as Felucca ported
it to integer C), precomputed so the firmware needs no float for them. The formulas are Felucca's
(tools/gen_tables.py, GPL-3.0-only, Leo Kuroshita / Hugelton Instruments), at 44.1 kHz in 32-sample blocks.
  python3 tools/gen_fm6_tables.py app/jungle/fm6_tables.h"""
